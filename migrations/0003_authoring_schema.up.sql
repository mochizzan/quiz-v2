-- 0003 — authoring schema: quizzes, questions, then answer_options.
-- Spec: docs/superpowers/specs/2026-10-23-schema-and-migrations-design.md §6.6, §6.7, §6.8.

CREATE TABLE IF NOT EXISTS quizzes (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  owner_account_id INT UNSIGNED NOT NULL,
  updated_by_account_id INT UNSIGNED NULL,
  title VARCHAR(150) NOT NULL,
  description VARCHAR(1000) NOT NULL DEFAULT '',
  visibility ENUM('public','private') CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'private',
  state ENUM('draft','open','closed') CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'draft',
  code CHAR(6) CHARACTER SET ascii COLLATE ascii_bin NULL,
  invite_token VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  target_grade TINYINT UNSIGNED NULL,
  target_major_id INT UNSIGNED NULL,
  starts_at DATETIME NULL,
  ends_at DATETIME NULL,
  allow_retake TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
  max_attempts TINYINT UNSIGNED NOT NULL DEFAULT 1,
  show_score TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
  review_mode VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'questions_only',
  randomize_questions TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
  randomize_options TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
  published_at DATETIME NULL,
  closed_at DATETIME NULL,
  deleted_by_account_id INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NOT NULL DEFAULT '1970-01-01 00:00:00',
  PRIMARY KEY (id),
  UNIQUE KEY uq_quizzes_code (code, deleted_at),
  UNIQUE KEY uq_quizzes_invite (invite_token, deleted_at),
  INDEX ix_quizzes_owner (owner_account_id, state, created_at),
  INDEX ix_quizzes_listing (state, visibility, created_at),
  CONSTRAINT fk_quizzes_owner FOREIGN KEY (owner_account_id) REFERENCES accounts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_quizzes_editor FOREIGN KEY (updated_by_account_id) REFERENCES accounts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_quizzes_major FOREIGN KEY (target_major_id) REFERENCES majors (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_quizzes_deleter FOREIGN KEY (deleted_by_account_id) REFERENCES accounts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_quizzes_code CHECK (code IS NULL OR code REGEXP '^[0-9]{6}$'),
  CONSTRAINT chk_quizzes_review_mode CHECK (review_mode IN ('questions_and_key','key_only','questions_only','answers_only')),
  CONSTRAINT chk_quizzes_attempts CHECK (max_attempts BETWEEN 0 AND 10),
  CONSTRAINT chk_quizzes_window CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at >= starts_at),
  CONSTRAINT chk_quizzes_target_grade CHECK (target_grade IS NULL OR target_grade BETWEEN 10 AND 12),
  CONSTRAINT chk_quizzes_target CHECK ((visibility = 'public' AND target_grade IS NULL AND target_major_id IS NULL) OR (visibility = 'private' AND target_grade IS NOT NULL AND target_major_id IS NOT NULL)),
  CONSTRAINT chk_quizzes_code_visibility CHECK ((visibility = 'public') = (code IS NOT NULL)),
  CONSTRAINT chk_quizzes_lifecycle CHECK (((state = 'draft') OR published_at IS NOT NULL) AND ((state = 'closed') = (closed_at IS NOT NULL))),
  CONSTRAINT chk_quizzes_allow_retake CHECK (allow_retake IN (0,1)),
  CONSTRAINT chk_quizzes_show_score CHECK (show_score IN (0,1)),
  CONSTRAINT chk_quizzes_randomize_questions CHECK (randomize_questions IN (0,1)),
  CONSTRAINT chk_quizzes_randomize_options CHECK (randomize_options IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS questions (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  quiz_id INT UNSIGNED NOT NULL,
  position SMALLINT UNSIGNED NOT NULL,
  type ENUM('single','multiple','essay') CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  prompt TEXT NOT NULL,
  updated_by_account_id INT UNSIGNED NULL,
  image_path VARCHAR(255) NULL,
  image_mime VARCHAR(50) CHARACTER SET ascii COLLATE ascii_bin NULL,
  image_bytes INT UNSIGNED NULL,
  image_sha256 BINARY(32) NULL,
  image_alt VARCHAR(255) NULL,
  deleted_by_account_id INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NOT NULL DEFAULT '1970-01-01 00:00:00',
  PRIMARY KEY (id),
  UNIQUE KEY uq_questions_position (quiz_id, position, deleted_at),
  CONSTRAINT fk_questions_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_questions_editor FOREIGN KEY (updated_by_account_id) REFERENCES accounts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_questions_deleter FOREIGN KEY (deleted_by_account_id) REFERENCES accounts (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_questions_position CHECK (position >= 1),
  CONSTRAINT chk_questions_image CHECK ((image_path IS NULL) = (image_mime IS NULL) AND (image_path IS NULL) = (image_bytes IS NULL) AND (image_path IS NULL) = (image_sha256 IS NULL)),
  CONSTRAINT chk_questions_mime CHECK (image_mime IS NULL OR image_mime IN ('image/jpeg','image/png','image/webp')),
  CONSTRAINT chk_questions_image_bytes CHECK (image_bytes IS NULL OR image_bytes <= 10485760)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS answer_options (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  question_id INT UNSIGNED NOT NULL,
  position SMALLINT UNSIGNED NOT NULL,
  body VARCHAR(500) NOT NULL,
  is_correct TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NOT NULL DEFAULT '1970-01-01 00:00:00',
  PRIMARY KEY (id),
  UNIQUE KEY uq_options_position (question_id, position, deleted_at),
  INDEX ix_options_correct (question_id, is_correct),
  CONSTRAINT fk_options_question FOREIGN KEY (question_id) REFERENCES questions (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_options_is_correct CHECK (is_correct IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
